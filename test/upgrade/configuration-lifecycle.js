const assert = require('assert')
const fs = require('fs')
const path = require('path')

const rootPath = path.resolve(__dirname, '../..')
const readProjectFile = filePath => fs.readFileSync(path.join(rootPath, filePath), 'utf8')

const generateFiles = readProjectFile('core/scripts/generate-files.ts')
const app = readProjectFile('core/app.ts')
const webpackBase = readProjectFile('core/build/webpack.base.config.ts')
const webpackClient = readProjectFile('core/build/webpack.client.config.ts')
const webpackServer = readProjectFile('core/build/webpack.server.config.ts')
const webpackServiceWorker = readProjectFile('core/build/webpack.prod.sw.config.ts')
const serviceWorkerGenerator = readProjectFile('core/build/generate-service-worker.js')
const devServer = readProjectFile('core/build/dev-server.js')
const server = readProjectFile('core/scripts/server.ts')
const containerEntrypoint = readProjectFile('docker/vue-storefront/vue-storefront.sh')
const packageManifest = JSON.parse(readProjectFile('package.json'))

assert.match(generateFiles, /core\/build\/config\.json|\.\.\/build\/config\.json/)
assert.match(generateFiles, /JSON\.stringify\(config\)/)
assert.match(app, /process\.env\.__APPVERSION__/)
assert.doesNotMatch(app, /process\.env\.APPVERSION/)
assert.match(webpackBase, /'process\.env\.BUILD': JSON\.stringify\('lib'\)/)
assert.match(webpackBase, /'process\.env\.__APPVERSION__'/)
assert.match(webpackBase, /'config': path\.resolve\(__dirname, '\.\/config\.json'\)/)
assert.match(webpackBase, /purge-config\/purgeConfigLoader\.ts/)

for (const webpackConfig of [webpackClient, webpackServer, webpackServiceWorker]) {
  assert.match(webpackConfig, /import base from '\.\/webpack\.base\.config'/)
}

assert.match(webpackServer, /vue-server-renderer\/server-plugin/)
assert.match(devServer, /vue-ssr-server-bundle\.json/)
assert.match(server, /vue-ssr-server-bundle\.json/)

assert.match(serviceWorkerGenerator, /workbox-build/)
assert.match(serviceWorkerGenerator, /inlineWorkboxRuntime: true/)
assert.match(serviceWorkerGenerator, /clientsClaim: false/)
assert.match(serviceWorkerGenerator, /skipWaiting: true/)
assert.match(serviceWorkerGenerator, /importScripts: \['\/dist\/core-service-worker\.js'\]/)
assert.match(serviceWorkerGenerator, /\['audio', 'video'\]\.includes\(request\.destination\)/)
assert.match(serviceWorkerGenerator, /handler: 'NetworkOnly'/)
assert.match(serviceWorkerGenerator, /\['', 'p', 'c', 'i'\]/)
assert.doesNotMatch(serviceWorkerGenerator, /\{ url: '\/', revision:/)
assert.match(serviceWorkerGenerator, /request\.destination === 'font'/)
assert.match(serviceWorkerGenerator, /request\.headers\.has\('range'\)/)
assert.doesNotMatch(serviceWorkerGenerator, /themeRelativePath/)
assert.doesNotMatch(serviceWorkerGenerator, /checkout|payment|\/api\//)

assert.match(server, /const config = require\('config'\)/)
assert.match(server, /process\.env\.PORT \|\| config\.server\.port/)
assert.match(server, /process\.env\.HOST \|\| config\.server\.host/)
assert.match(server, /process\.env\.KEEP_ALIVE_TIMEOUT \|\| config\.server\.keepAliveTimeout/)

const configTemplatePosition = containerEntrypoint.indexOf('envsubst < config/local.json.template')
const buildPosition = containerEntrypoint.indexOf('yarn build')
assert(configTemplatePosition >= 0 && configTemplatePosition < buildPosition)
assert.match(containerEntrypoint, /yarn install --immutable/)
assert.strictEqual(packageManifest.packageManager, 'yarn@4.17.1')
assert.match(packageManifest.scripts.build, /^rimraf dist &&/)

console.log('Configuration lifecycle assertions passed')
