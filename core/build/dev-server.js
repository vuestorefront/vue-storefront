const path = require('path')
const webpack = require('webpack')
const { createFsFromVolume, Volume } = require('memfs')
const { createVueTscWatchCoordinator } = require('./vue-tsc-watch-coordinator')

let baseClientConfig = require('./webpack.client.config').default
let baseServerConfig = require('./webpack.server.config').default

const themeRoot = require('./theme-path')
const extendedConfig = require(path.join(themeRoot, '/webpack.config.js'))

let clientConfig = extendedConfig(baseClientConfig, { isClient: true, isDev: true })
let serverConfig = extendedConfig(baseServerConfig, { isClient: false, isDev: true })

function createMemoryFileSystem () {
  const fileSystem = createFsFromVolume(new Volume())
  fileSystem.join = path.join.bind(path)
  fileSystem.mkdirp = (directory, callback) => fileSystem.mkdir(directory, { recursive: true }, callback)
  return fileSystem
}

module.exports = function setupDevServer (app, cb) {
  let bundle
  let template
  let typeCheckCoordinator

  function updateRenderer () {
    if (!bundle || !template) {
      return
    }

    cb(bundle, template)
    typeCheckCoordinator.markRendererReady()
  }

  // Modify client config to work with hot middleware
  clientConfig.entry.app = ['webpack-hot-middleware/client', ...clientConfig.entry.app]
  clientConfig.output.filename = '[name].js'
  clientConfig.plugins.push(
    new webpack.HotModuleReplacementPlugin(),
    new webpack.NoEmitOnErrorsPlugin()
  )

  // Dev middleware
  const clientCompiler = webpack(clientConfig)
  const serverCompiler = webpack(serverConfig)
  typeCheckCoordinator = createVueTscWatchCoordinator({
    compilers: {
      client: clientCompiler,
      server: serverCompiler
    }
  })
  typeCheckCoordinator.start()

  const devMiddleware = require('webpack-dev-middleware')(clientCompiler, {
    publicPath: clientConfig.output.publicPath,
    stats: 'minimal'
  })
  app.use(devMiddleware)
  clientCompiler.hooks.done.tap('VueStorefrontDevServer', (stats) => {
    if (stats.hasErrors()) {
      return
    }

    const fs = devMiddleware.context.outputFileSystem
    const filePath = path.join(clientConfig.output.path, 'index.html')
    if (fs.existsSync(filePath)) {
      template = fs.readFileSync(filePath, 'utf-8')
      updateRenderer()
    }
  })

  // Hot middleware
  app.use(require('webpack-hot-middleware')(clientCompiler))

  // watch and update server renderer
  const mfs = createMemoryFileSystem()
  serverCompiler.outputFileSystem = mfs
  serverCompiler.watch({}, (err, stats) => {
    if (err) {
      console.error(err)
      return
    }

    const compilation = stats.toJson({ all: false, errors: true, warnings: true })
    compilation.errors.forEach(error => console.error(error))
    compilation.warnings.forEach(warning => console.warn(warning))

    if (stats.hasErrors()) {
      return
    }

    // Read bundle generated by vue-server-renderer/server-plugin
    const bundlePath = path.join(serverConfig.output.path, 'vue-ssr-server-bundle.json')
    bundle = JSON.parse(mfs.readFileSync(bundlePath, 'utf-8'))
    updateRenderer()
  })
}
